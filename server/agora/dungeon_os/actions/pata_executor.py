"""PATA Executor — real implementation actions for the execution phase.

Phase 4: Instead of logging a plan file, the PATA phase actually
produces real artifacts:

Designer:
  - Architecture Decision Record (ADR) in the repo's design docs
  - Technical design specification
  - Code structure outline / interface definitions

Developer:
  - LLM-generates actual source code based on the design
  - Writes files to the target codebase
  - Runs syntax checks and existing tests
  - Creates a git commit with the change

QA:
  - Validates generated code (syntax, type checks)
  - Verifies files exist
  - Checks implementation against success criteria
  - Reports pass/fail with evidence
"""

