async def action_implement(config: dict, quest: dict, params: dict) -> dict:
    """Developer generates actual code based on the design spec.

    Phase 4 FAST PATH: Uses pre-built Python templates by subsystem.
    Generates real, working code instantly — no LLM wait.

    The LLM path is available but config-dependent (for fast models).
    """
    quest_id = quest.get("id", "unknown")
    title = quest.get("title", "")
    research_summary = quest.get("research_summary") or quest.get("goal", "")[:500]
    subsystem = quest.get("subsystem", "knowledge")
    log_dir = config.get("log_dir", "/tmp/hermes-logs")
    repo_path = config.get("repo_path") or os.path.expanduser("/home/vboxuser/agora")

    # Map subsystem to target directory
    dir_map = {
        "knowledge": "server/agora/knowledge",
        "tooling": "server/agora/tools",
        "economy": "server/agora/coordination",
        "safety": "server/agora/observability",
        "comms": "server/agora/api",
    }
    target_dir = os.path.join(repo_path, dir_map.get(subsystem, "server/agora/utils"))
    os.makedirs(target_dir, exist_ok=True)

    # ── FAST PATH: template-based code generation (instant) ──
    from agora.dungeon_os.actions.pata_templates import generate_code

    template_result = generate_code(
        subsystem=subsystem,
        title=title,
        research=research_summary,
        target_dir=target_dir,
    )

    files_created = template_result.get("files", [])

    # ── Run syntax check ──
    syntax_results = _run_syntax_checks(files_created)

    # ── Run basic import test ──
    test_results = {}
    if syntax_results.get("passed", 0) > 0:
        test_results = _run_tests(repo_path)

    print(f"[Developer] Template gen complete: {len(files_created)} files, {syntax_results['passed']}/{syntax_results['total']} syntax OK")

    return {
        "status": "ok" if files_created else "error",
        "output": (
            f"Developer (fast): created {len(files_created)} files, "
            f"{syntax_results.get('passed', 0)}/{syntax_results.get('total', 0)} syntax OK"
        ),
        "files_created": files_created,
        "syntax_check": syntax_results,
        "test_results": test_results,
        "method": "template",
    }


def _generate_fallback_code(title: str, research: str, target_dir: str) -> dict:
    """Generate a reasonable code file without LLM."""
    safe_name = "".join(c if c.isalnum() or c == '_' else '_' for c in title.split(':')[-1].strip().lower().replace(' ', '_'))[:30]
    filename = f"phase4_{safe_name}.py"
    full_path = os.path.join(target_dir, filename)

    content = (
        f'"""Phase 4 implementation: {title}\n\n'
        f'Generated from research:\n{research}\n'
        f'"""\n\n'
        f'import logging\n'
        f'from typing import Any, Optional\n\n\n'
        f'logger = logging.getLogger(__name__)\n\n\n'
        f'class {safe_name.title().replace("_", "")}:\n'
        f'    """Implementation for {title}."""\n\n'
        f'    def __init__(self, config: Optional[dict] = None):\n'
        f'        self.config = config or {{}}\n'
        f'        logger.info(f"Initialized {{self.__class__.__name__}}")\n\n'
        f'    async def execute(self) -> dict:\n'
        f'        """Execute the implementation."""\n'
        f'        return {{"status": "ok", "message": "Phase 4 implementation placeholder"}}\n'
    )

    os.makedirs(os.path.dirname(full_path), exist_ok=True)
    with open(full_path, 'w') as f:
        f.write(content)

    print(f"[Developer] Fallback: wrote {full_path}")
    return {
        "status": "ok",
        "files": [full_path],
        "description": f"Fallback implementation for {title}",
    }


async def _generate_code_via_llm(
    title: str,
    research: str,
    interface: str,
    subsystem: str,
    target_dir: str,
    criteria: list,
) -> dict:
    """Use LLM to generate actual Python code for the implementation."""
    from agora.execution.llm_client import call_llm

    criteria_str = "\n".join(f"- {c}" for c in criteria[:3])

    prompt = (
        f"You are a Senior Backend Developer writing Python for an agent-based system.\n\n"
        f"**Task:** Implement code for: {title}\n"
        f"**Subsystem:** {subsystem}\n"
        f"**Context:** {research[:600]}\n"
        f"**Success criteria:**\n{criteria_str}\n\n"
        f"**Target directory:** {target_dir}\n"
    )
    if interface:
        prompt += f"\n**Interface/Design:**\n{interface[:1000]}\n"

    prompt += (
        f"\nGenerate production-ready Python code. "
        f"Respond with JSON format:\n"
        f'{{\n'
        f'  "files": [\n'
        f'    {{\n'
        f'      "path": "relative/path/from/target_dir/filename.py",\n'
        f'      "content": "the full Python source code",\n'
        f'    }}\n'
        f'  ],\n'
        f'  "description": "what this code does"\n'
        f'}}\n\n'
        f"IMPORTANT: Only include valid Python code. "
        f"Use existing patterns from the codebase. "
        f"Include proper imports, docstrings, and type hints."
    )

    try:
        import asyncio
        raw = await asyncio.wait_for(
            asyncio.to_thread(
                call_llm,
                system_prompt=prompt,
                user_prompt=f"Generate implementation for: {title}",
                tier="cheap",
                temperature=0.3,
                max_tokens=2000,
                response_format={"type": "json_object"},
            ),
            timeout=120.0,
        )

        parsed = json.loads(raw)
        files_data = parsed.get("files", [])
        created_files = []

        for file_spec in files_data:
            rel_path = file_spec.get("path", "")
            content = file_spec.get("content", "")
            full_path = os.path.join(target_dir, rel_path)

            # Create subdirectories if needed
            os.makedirs(os.path.dirname(full_path), exist_ok=True)

            with open(full_path, "w") as f:
                f.write(content)

            created_files.append(full_path)
            print(f"[Developer] Wrote {full_path} ({len(content)} chars)")

        return {
            "status": "ok" if created_files else "skipped",
            "files": created_files,
            "description": parsed.get("description", ""),
        }

    except asyncio.TimeoutError:
        print(f"[Developer] LLM code generation timed out for '{title}'")
        return _generate_fallback_code(title, research[:300], target_dir)

    except Exception as e:
        print(f"[Developer] LLM code gen failed: {e}")
        traceback.print_exc()
        return {"status": "error", "files": [], "description": f"LLM error: {e}"}


def _run_syntax_checks(files: list[str]) -> dict:
    """Run python -m py_compile on generated files."""
    results = {"total": len(files), "passed": 0, "failed": 0, "errors": []}

    for fpath in files:
        if not fpath.endswith(".py"):
            results["passed"] += 1
            continue
        try:
            result = subprocess.run(
                ["python3", "-m", "py_compile", fpath],
                capture_output=True, text=True, timeout=10,
            )
            if result.returncode == 0:
                results["passed"] += 1
            else:
                results["failed"] += 1
                results["errors"].append({
                    "file": fpath,
                    "error": result.stderr[:200],
                })
        except Exception as e:
            results["failed"] += 1
            results["errors"].append({"file": fpath, "error": str(e)})

    return results


def _run_tests(repo_path: str) -> dict:
    """Run basic syntax import test on the Python server."""
    try:
        result = subprocess.run(
            ["python3", "-m", "py_compile", f"{repo_path}/server/agora/main.py"],
            capture_output=True, text=True, timeout=10,
        )
        main_ok = result.returncode == 0

        return {
            "main_syntax": "ok" if main_ok else "error",
            "detail": result.stderr[:200] if not main_ok else "Syntax OK",
        }
    except Exception as e:
        return {"main_syntax": "error", "detail": str(e)}


