"""build_v4_naturalized.py — the naturalized coreference-reversion fixture (v4-nat), the arena Marat asked for.

Templated v4 proved the two-hop coreference chain is the real signal, but its fixed "X owns Y" lines and 8
candidate templates let a model learn surface grammar (v4's first two cuts were beaten by exactly that: an
anchor-name substring, then a template-parity artifact). This set keeps the SAME structure (candidate refers to
an anchor by ROLE, no name / no value / no revert word; label = whether that anchor set the OLD value) but the
surfaces are richly varied natural phrasings, split TRAIN vs HELDOUT by REGISTER so the test phrasings are ones
no model has seen.

The phrasings are AUTHORED HERE (by the assistant), not generated by a weaker cloud model: higher quality,
instant, deterministic. Ground truth comes from STRUCTURE, not text. Two disjoint registers:
  TRAIN  = register A, terse ops-chat / standup shorthand
  HELDOUT = register B, discursive narrative prose
A surface-pattern learner trained on A should not transfer to B; a real chain-follower should.

Fairness asserts (same discipline as templated v4): candidate never contains an anchor name, a value token, or a
revert/keep/positional keyword; candidate template is chosen RANDOMLY, independent of the label (kills template
parity); anchors and roles are pool-balanced old/current. Deterministic (seed). No network, no LLM.
RUN: python mnemo/probes/build_v4_naturalized.py
"""
