def _has_kw(t):
    tl = t.lower()
    return any(w in tl for w in REVERT_KW + KEEP_KW)


def deranged(pool):
    a = [x for x in pool for _ in range(5)]
    b = [x for x in pool for _ in range(5)]
    for _ in range(20000):
        random.shuffle(a); random.shuffle(b)
        if all(x != y for x, y in zip(a, b)):
            return a, b
    raise RuntimeError("no derangement")


def build_split(register, cand_pool, ctx_pool, per_kind):
    a_old, a_cur = deranged(ANCHORS)
    r_old, r_cur = deranged(ROLES)
    rows, pi = [], 0
    plan = (["obscuring_revert"] * per_kind + ["obscuring_keep"] * per_kind
            + ["named_new"] * max(6, per_kind // 3))
    random.shuffle(plan)
    for kind in plan:
        entity, old, cur = ENTS[pi % len(ENTS)]
        ao, ac = a_old[pi % len(a_old)], a_cur[pi % len(a_cur)]
        ro, rc = r_old[pi % len(r_old)], r_cur[pi % len(r_cur)]; pi += 1
        if ao == ac or ro == rc:
            continue
        if kind == "obscuring_revert":
            rt, label = ro, 1
        elif kind == "obscuring_keep":
            rt, label = rc, 0
        else:
            rt = random.choice([r for r in ROLES if r not in (ro, rc)]); label = 0
        ctx = [ln.format(ent=entity, old=old, cur=cur, aold=ao, acur=ac, rold=ro, rcur=rc)
               for ln in random.choice(ctx_pool)]
        rows.append({"entity": entity, "old_value": old, "current_value": cur, "anchor_old": ao,
                     "anchor_current": ac, "role_old": ro, "role_current": rc, "role_target": rt,
                     "context": ctx, "candidate": None, "kind": kind, "reopens_stale": label,
                     "register": register})
    # STRATIFIED candidate assignment: round-robin a shuffled pool WITHIN each label group, so every candidate
    # skeleton appears ~equally for label 0 and label 1 -> template can't predict the label (by construction).
    for label in (0, 1):
        grp = [r for r in rows if r["reopens_stale"] == label]
        pool = cand_pool[:]; random.shuffle(pool)
        for i, r in enumerate(grp):
            r["candidate"] = pool[i % len(pool)].format(r=r["role_target"])
    return rows


def main():
    train = build_split("A", CAND_A, CTX_A, per_kind=25)
    heldout = build_split("B", CAND_B, CTX_B, per_kind=20)
    for i, r in enumerate(train):
        r["split"] = "train"
    for r in heldout:
        r["split"] = "heldout"
    allrows = train + heldout
    random.shuffle(allrows)
    for i, r in enumerate(allrows):
        r["id"] = i

    # ── fairness asserts ──────────────────────────────────────────────────────
    for r in allrows:
        c = r["candidate"].lower()
        assert not _has_kw(c), f"keyword leaked: {c!r}"
        assert r["old_value"] not in c and r["current_value"] not in c, f"value leaked: {c!r}"
        # strip the (legitimately-named) role_target before checking for an anchor-name leak, so an anchor
        # that merely shares a token with the role (e.g. "the vendor" vs role "vendor contracts") is not a
        # false positive — the role is SUPPOSED to be named; the anchor must not be.
        c_norole = c.replace(r["role_target"].lower(), " ")
        assert r["anchor_old"].lower().replace("the ", "") not in c_norole \
            and r["anchor_current"].lower().replace("the ", "") not in c_norole, f"anchor name leaked: {c!r}"
        assert r["anchor_old"] != r["anchor_current"] and r["role_old"] != r["role_current"], "degenerate"
        # each value must sit only in its own context line (so the audit can identify old vs current)
        joined = " ".join(r["context"]).lower()
        assert r["old_value"] in joined and r["current_value"] in joined, "value dropped from context"
    # template-parity guard: within obscuring rows, no candidate skeleton predicts the label
    def sig(cand):
        s = cand.lower()
        for role in sorted(ROLES, key=len, reverse=True):
            s = s.replace(role, "{r}")
        return s
    tab = {}
    for r in allrows:
        if r["kind"] == "named_new":
            continue
        s = sig(r["candidate"]); a, b = tab.get(s, (0, 0)); tab[s] = (a + r["reopens_stale"], b + 1)
    for s, (ones, tot) in tab.items():
        share = ones / tot
        assert 0.15 <= share <= 0.85 or tot <= 2, f"candidate skeleton predicts label ({share:.2f}, n={tot}): {s!r}"

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        for r in allrows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    from collections import Counter
    print(f"wrote {len(allrows)} rows -> {OUT}")
    print("split:", dict(Counter(r["split"] for r in allrows)), "| kind:", dict(Counter(r["kind"] for r in allrows)))
    print(f"distinct candidate skeletons: {len(set(sig(r['candidate']) for r in allrows))}")
    for r in allrows[:4]:
        print(f"  [{r['split']}/{r['kind']}/L{r['reopens_stale']}] {r['candidate']!r}")
        print(f"      ctx: {r['context']}")


if __name__ == "__main__":
    main()
